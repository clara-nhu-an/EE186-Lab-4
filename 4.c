static uint32_t ReadLight(void)
{
    if (HAL_ADC_Start(&hadc1) != HAL_OK) Error_Handler();
    if (HAL_ADC_PollForConversion(&hadc1, 100) != HAL_OK) Error_Handler();
    uint32_t value = HAL_ADC_GetValue(&hadc1);
    if (HAL_ADC_Stop(&hadc1) != HAL_OK) Error_Handler();
    adc_raw = value;
    return value;
}

void changeNote(uint32_t frequency)
{
    if (frequency < 100U) frequency = 100U;
    if (frequency > 1000U) frequency = 1000U;
    /* 32-bit phase accumulator: cycles/sample = frequency/sample rate.
       Compute outside ISR; a single aligned 32-bit store publishes the step.
       Do not reset phase when changing frequency, avoiding phase discontinuities. */
    uint32_t step = (uint32_t)((((uint64_t)frequency << 32) + SAMPLE_RATE_HZ/2U)
                               / SAMPLE_RATE_HZ);
    phase_step = step;
    note_hz = frequency;
}

static void CalibrateLight(void)
{
    char message[100];
    sensor_low = 4095;
    sensor_high = 0;
    Serial_Print("CALIBRATE: cover and uncover the LDR for 5 seconds now.\r\n");
    uint32_t start = HAL_GetTick();
    while ((uint32_t)(HAL_GetTick() - start) < CALIBRATION_MS) {
        uint32_t value = ReadLight();
        if (value < sensor_low) sensor_low = value;
        if (value > sensor_high) sensor_high = value;
        HAL_Delay(5);
    }
    if (sensor_high - sensor_low < 64U) {
        Serial_Print("Small light change: using 0..4095. Check wiring and RESET to retry.\r\n");
        sensor_low = 0;
        sensor_high = 4095;
    }
    snprintf(message, sizeof(message), "Calibration: low=%lu high=%lu\r\n",
             (unsigned long)sensor_low, (unsigned long)sensor_high);
    Serial_Print(message);
}
